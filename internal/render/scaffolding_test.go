func TestRenderReadmeFromSource(t *testing.T) {
	// given: petstore rendered without homebrew distribution
	doc, err := spec.Load(ladder + "petstore.yaml")
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	api := mapping.Map(doc, nil)
	cfg := &config.Config{Output: config.Output{Module: "example.com/petstore-cli"}}
	files, err := Render(api, cfg, Provenance{SpecPath: "petstore.yaml", SpecSHA256: "test"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}

	// then: the README carries the marker, a from-source install block, usage
	// and completions sections, and no homebrew section
	readme := string(findFile(t, files, "README.md").Contents)
	for _, want := range []string{
		"<!-- Code generated by biscuit. DO NOT EDIT. -->",
		"# swagger-petstore",
		"go install example.com/petstore-cli/cmd/swagger-petstore@latest",
		"swagger-petstore --help",
		"swagger-petstore completion bash|zsh|fish|powershell",
	} {
		if !strings.Contains(readme, want) {
			t.Errorf("README.md missing %q:\n%s", want, readme)
		}
	}
	if strings.Contains(readme, "Homebrew 6") {
		t.Error("README.md documents the Homebrew trust step with Homebrew=false")
	}
}

